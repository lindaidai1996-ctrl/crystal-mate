export type MarketCopy = (typeof marketCopy)['zh'];

export function getMarketCopy(locale: 'zh' | 'en', metal: 'silver' | 'gold'): MarketCopy {
  const copy = marketCopy[locale];
  if (metal === 'silver') return copy;
  return locale === 'zh'
    ? {
        ...copy,
        title: '今日金价',
        latest: '最新金价',
        refreshUnchanged: '已刷新，金价暂无变化',
        history: '历史金价走势',
        chartLabel: '黄金历史每日收盘价，单位元每克',
        source: '数据来源：东方财富 · 上海黄金交易所 Au(T+D)',
        note: '行情可能存在延迟；历史图为交易日日线，当日数据随行情更新。大盘参考价与金饰成品报价不同。',
      }
    : {
        ...copy,
        title: 'Gold, today.',
        latest: 'LATEST GOLD PRICE',
        refreshUnchanged: 'Refreshed. The gold price is unchanged.',
        history: 'Gold through time',
        chartLabel: 'Daily gold closing prices in CNY per gram',
        source: 'Source: Eastmoney · Shanghai Gold Exchange Au(T+D)',
      };
}
